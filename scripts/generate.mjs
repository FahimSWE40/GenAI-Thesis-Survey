// Generates supabase/schema.sql and CODEBOOK.md from public/questions.js.
// Run after editing questions:  npm run generate
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECTIONS, SCREENING, LIKERT_LABELS, FORM_VERSION, fieldList } from '../public/questions.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FIELDS = fieldList();
const sqlStr = s => `'${String(s).replace(/'/g, "''")}'`;

// ---------- schema.sql ----------
const cols = [];
const comments = [];
for (const f of FIELDS) {
  const label = `${f.q.id}: ${f.kind === 'likert' ? f.q.en : f.q.en}`;
  if (f.kind === 'likert') {
    cols.push(`  ${f.col} smallint not null check (${f.col} between 1 and 5)`);
    comments.push(`comment on column public.responses.${f.col} is ${sqlStr(label + (f.q.reverse ? ' [REVERSE-CODED]' : '') + (f.q.attention ? ` [ATTENTION CHECK: correct = ${f.q.attention}]` : ''))};`);
  } else if (f.kind === 'single') {
    const vs = f.q.options.map(o => o.v);
    cols.push(`  ${f.col} smallint${f.q.optional ? '' : ' not null'} check (${f.col} between ${Math.min(...vs)} and ${Math.max(...vs)})`);
    comments.push(`comment on column public.responses.${f.col} is ${sqlStr(label + ' | ' + f.q.options.map(o => `${o.v}=${o.en}`).join('; ') + (f.q.optional ? ' | OPTIONAL (blank = no answer)' : ''))};`);
  } else if (f.kind === 'multi') {
    cols.push(`  ${f.col} text[] not null`);
    comments.push(`comment on column public.responses.${f.col} is ${sqlStr(label + ' | multi-select: ' + f.q.options.map(o => o.v).join(', '))};`);
  } else if (f.kind === 'text') {
    cols.push(`  ${f.col} text not null check (char_length(${f.col}) between 2 and ${f.q.maxLength || 150})`);
    comments.push(`comment on column public.responses.${f.col} is ${sqlStr(label + ' | typed answer')};`);
  } else if (f.kind === 'other_text') {
    cols.push(`  ${f.col} text check (char_length(${f.col}) <= 200)`);
  }
}

const likertSections = SECTIONS.filter(s => s.kind === 'likert');
const viewCols = ['id', 'created_at', 'started_at', 'duration_sec', 'form_version', 'ui_lang', 'attention_pass',
  'respondent_id', 'ip_hash', 'device_type', 'src', 'receipt_code', 'bot_check',
  'exists (select 1 from public.withdrawals w where w.receipt_code = responses.receipt_code) as withdrawn'];
for (const f of FIELDS) {
  if (f.kind === 'multi') {
    for (const o of f.q.options) viewCols.push(`(case when ${sqlStr(o.v)} = any(${f.col}) then 1 else 0 end) as ${f.col}_${o.other ? "other_selected" : o.v}`);
  } else {
    viewCols.push(f.col);
  }
  if (f.kind === 'likert' && f.q.reverse) viewCols.push(`(6 - ${f.col}) as ${f.col}_r`);
}
for (const s of likertSections) {
  const its = s.items.filter(i => !i.attention);
  const terms = its.map(i => (i.reverse ? `(6 - ${i.id.toLowerCase()})` : i.id.toLowerCase()));
  viewCols.push(`round((${terms.join(' + ')})::numeric / ${its.length}, 3) as ${s.short}_mean`);
}

const schema = `-- GenAI Dependence survey — Supabase schema (form version ${FORM_VERSION})
-- GENERATED by scripts/generate.mjs from public/questions.js. Do not edit by hand.
-- Run once in Supabase: Dashboard → SQL Editor → paste → Run.

create table if not exists public.responses (
  id             bigint generated always as identity primary key,
  submission_id  uuid not null unique,
  created_at     timestamptz not null default now(),
  started_at     timestamptz,
  duration_sec   integer,
  form_version   text not null,
  ui_lang        text,
  attention_pass boolean,
  -- data-authenticity fields (no personal data)
  respondent_id  uuid,                 -- random ID kept in the participant's browser (same device = same ID)
  ip_hash        text,                 -- one-way salted SHA-256 of the IP address; the IP itself is never stored
  device_type    text check (device_type in ('mobile', 'tablet', 'desktop', 'unknown')),
  src            text check (src ~ '^[a-z0-9_-]{1,60}$'),   -- recruitment source tag from the shared link
  receipt_code   text not null unique, -- shown to the participant; used for withdrawal requests
  bot_check      text check (bot_check in ('passed', 'not_configured')),
${cols.join(',\n')}
);

-- Only the server (service-role key, used by /api/submit) can read or write.
-- RLS on + no policies = the public anon key has no access at all.
alter table public.responses enable row level security;
revoke all on public.responses from anon, authenticated;
revoke all on public.responses from service_role;
grant select, insert on public.responses to service_role;   -- the form's server may only add rows (and read for the health check)

-- Append-only: once saved, a response can never be edited or deleted (not even by the researcher).
-- Removing this protection would require a new migration, which Supabase records in its history.
create or replace function public.responses_block_changes()
returns trigger language plpgsql set search_path = '' as $$
begin
  raise exception 'responses are append-only: % is not allowed', tg_op;
end;
$$;
drop trigger if exists responses_no_update_delete on public.responses;
create trigger responses_no_update_delete before update or delete on public.responses
  for each row execute function public.responses_block_changes();
drop trigger if exists responses_no_truncate on public.responses;
create trigger responses_no_truncate before truncate on public.responses
  for each statement execute function public.responses_block_changes();

-- Withdrawals are recorded here instead of deleting data; exclude them in analysis (view column "withdrawn").
create table if not exists public.withdrawals (
  id            bigint generated always as identity primary key,
  receipt_code  text not null unique,
  requested_at  timestamptz not null default now(),
  note          text
);
alter table public.withdrawals enable row level security;
revoke all on public.withdrawals from anon, authenticated;
revoke all on public.withdrawals from service_role;   -- researcher-only (SQL Editor); the server never needs it

${comments.join('\n')}

-- Analysis-ready view: multi-select answers expanded to 0/1 columns,
-- reverse-coded items added as *_r, and construct mean scores.
create or replace view public.responses_spss
with (security_invoker = true) as
select
  ${viewCols.join(',\n  ')}
from public.responses;

revoke all on public.responses_spss from anon, authenticated;
revoke all on public.responses_spss from service_role;   -- export in the SQL Editor; not exposed to the server
notify pgrst, 'reload schema';   -- let the API see the new tables immediately
`;
mkdirSync(join(root, 'supabase'), { recursive: true });
writeFileSync(join(root, 'supabase', 'schema.sql'), schema);

// ---------- CODEBOOK.md ----------
let md = `# Codebook — GenAI Dependence Survey (form version ${FORM_VERSION})

*Generated from \`public/questions.js\` by \`npm run generate\`. Column names are the lower-case item codes.*

## Screening (not stored)

Only participants who answer **Yes** to all three are allowed to continue; nothing is saved for anyone screened out.

| Code | Question |
|---|---|
${SCREENING.map(q => `| ${q.id} | ${q.en} |`).join('\n')}

## Metadata columns

| Column | Meaning |
|---|---|
| id | Row number |
| submission_id | Random ID made by the browser (prevents duplicate saves) |
| created_at | When the response was saved (UTC) |
| started_at | When the participant started the form (UTC) |
| duration_sec | Seconds from start to submit — flag responses under ~300 s |
| form_version | Questionnaire version |
| ui_lang | Language view used: en / bn / both |
| attention_pass | true if ATT = 4 (Agree) and ATT2 = 2 (Disagree) |
| respondent_id | Random ID stored in the participant's browser — the same device/browser always sends the same ID (detects repeat submissions) |
| ip_hash | One-way salted SHA-256 code of the internet connection; the IP address is never stored and cannot be recovered |
| device_type | mobile / tablet / desktop / unknown (from the browser's user agent) |
| src | Recruitment source tag from the link, e.g. \`?src=diu-cse-whatsapp\` |
| receipt_code | Code shown to the participant after submitting; used to request withdrawal |
| bot_check | \`passed\` = Cloudflare Turnstile verified a human; \`not_configured\` = check was off |
| withdrawn | (view only) true if the participant withdrew using their receipt code — exclude these rows |

`;
for (const s of SECTIONS) {
  md += `## Section ${s.id}: ${s.en}${s.construct ? ` — ${s.construct}` : ''}\n\n`;
  if (s.kind === 'likert') {
    md += `Scale: ${(s.scale || LIKERT_LABELS).map(l => `${l.v} = ${l.en}`).join(', ')}${s.scale ? ' (higher = more human-oriented)' : ''}\n\n| Column | Item | Note |\n|---|---|---|\n`;
    for (const it of s.items) md += `| ${it.id.toLowerCase()} | ${it.en} | ${it.reverse ? 'Reverse-coded → use ' + it.id.toLowerCase() + '_r' : it.attention ? `Attention check (correct = ${it.attention})` : ''} |\n`;
  } else {
    md += `| Column | Question | Values |\n|---|---|---|\n`;
    for (const q of s.questions) {
      const vals = q.type === 'text' ? `Typed answer (2–${q.maxLength || 150} characters) — clean/standardise spelling before analysis`
        : q.type === 'multi'
        ? 'Multi-select (text array). In `responses_spss`: ' + q.options.map(o => `${q.id.toLowerCase()}_${o.other ? "other_selected" : o.v}`).join(', ') + ' (0/1)'
        : q.options.map(o => `${o.v} = ${o.en}`).join('; ');
      md += `| ${q.id.toLowerCase()} | ${q.en} | ${vals} |\n`;
      if (q.options && q.options.some(o => o.other)) md += `| ${q.id.toLowerCase()}_other | "Other" text for ${q.id} | Free text (≤ 200 chars) |\n`;
    }
  }
  md += '\n';
}
md += `## Construct mean scores (in \`responses_spss\`)

${likertSections.map(s => {
  const its = s.items.filter(i => !i.attention);
  return `- **${s.short}_mean** — ${s.construct}: mean of ${its.map(i => i.id + (i.reverse ? ' (reversed)' : '')).join(', ')}`;
}).join('\n')}

> Use the item-level columns (not the means) as indicators in SmartPLS.
`;
writeFileSync(join(root, 'CODEBOOK.md'), md);
console.log('Wrote supabase/schema.sql and CODEBOOK.md');
