const SMALL = new Set(['of', 'and', 'the', 'for']);
const clean = s => s.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();

export const UNIVERSITIES = [...PUBLIC.map(n => [n, 'public']), ...PRIVATE.map(n => [n, 'private'])].map(([label, type]) => {
  const name = label.replace(/\s*\(formerly [^)]*\)/, '').trim();          // value stored in DEM3
  const words = name.replace(/\(.*?\)/g, '').split(/[\s,-]+/).filter(w => w && !SMALL.has(w.toLowerCase()));
  const acronym = words.map(w => w[0]).join('').toLowerCase();           // e.g. Daffodil International University → diu
  const aliases = (ALIASES[name] || '').split(';').map(clean).filter(Boolean);
  return { name, label, type, search: clean(`${label} ${aliases.join(' ')}`), aliases, acronym };
});

// Best matches first: exact short name, then names starting with the text, then names containing every typed word.
export function searchUniversities(query, limit = 8) {
  const q = clean(query);
  if (!q) return [];
  const words = q.split(' ');
  const scored = [];
  for (const u of UNIVERSITIES) {
    const tokens = u.search.split(' ');
    let score = -1;
    if (u.acronym === q || u.aliases.includes(q)) score = 0;
    else if (u.aliases.some(a => a.startsWith(q))) score = 0.5;   // e.g. "dhaka univ" → University of Dhaka first
    else if (u.search.startsWith(q) || tokens.includes(q)) score = 1;
    else if (words.every(w => tokens.some(t => t.startsWith(w)))) score = 2;
    else if (words.every(w => u.search.includes(w))) score = 3;
    if (score >= 0) scored.push([score, u]);
  }
  scored.sort((a, b) => a[0] - b[0] || a[1].name.localeCompare(b[1].name));
  return scored.slice(0, limit).map(x => x[1]);
}
